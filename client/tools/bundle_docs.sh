#!/usr/bin/env bash
# Bundles the tester-facing docs into the client so the in-client Help window
# (scripts/ui/help_window.gd) can read them from res://docs/ at runtime.
#
# The repo copies under docs/ are the source of truth; this copies them into
# client/docs/ and generates a RELEASE_NOTES.md from the most recent git tags.
# The client/docs/ copies are committed, because the release build runs on a
# runner whose checkout may be shallow (no tags) -- so the shipped notes are a
# snapshot taken when this ran, which the file itself states.
#
# Run it from anywhere in the repo after editing docs/DEBUG_TOOLS.md or
# docs/HELP_PLAYING.md, or to refresh the release notes before a release.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
src="$repo_root/docs"
dst="$repo_root/client/docs"
mkdir -p "$dst"

for f in DEBUG_TOOLS.md HELP_PLAYING.md; do
  cp "$src/$f" "$dst/$f"
  echo "bundled $f"
done

notes="$dst/RELEASE_NOTES.md"
{
  echo "# Release notes"
  echo
  echo "_Snapshot of the most recent release tags, generated by"
  echo "client/tools/bundle_docs.sh. A build from a shallow checkout keeps this"
  echo "committed snapshot rather than an empty file._"
  echo
  if git -C "$repo_root" tag >/dev/null 2>&1 && [ -n "$(git -C "$repo_root" tag)" ]; then
    # Newest first: the last ~20 version tags, each with its full changelog --
    # the title and every change under it -- from docs/release_notes/<tag>.md,
    # or the tag's own message for releases older than those files
    # (client/tools/release_notes.sh). Testers read the changes here, not on
    # GitHub (playtest feedback, 2026-09-25; the user, 2026-10-28: "include
    # the changes in the changelog in the game").
    while IFS= read -r tag; do
      notes_md="$(bash "$repo_root/client/tools/release_notes.sh" "$tag")"
      subject="$(printf '%s\n' "$notes_md" | head -n1)"
      body="$(printf '%s\n' "$notes_md" | tail -n +2 | awk 'NF{p=1} p')"
      date="$(git -C "$repo_root" log -1 --format=%ad --date=short "$tag" 2>/dev/null || true)"
      echo "## $tag${date:+ ($date)}"
      echo
      # The title usually begins with the tag itself ("v0.1.439: rounds
      # 549-551"); under a heading that already names the tag, print the rest.
      subject="${subject#"$tag": }"
      subject="${subject#"$tag" }"
      [ "$subject" = "$tag" ] && subject=""
      echo "${subject:-(no message)}"
      if [ -n "$body" ]; then
        echo
        printf '%s\n' "$body"
      fi
      echo
    done < <(git -C "$repo_root" tag --sort=-creatordate | grep -E '^v[0-9]' | head -20)
  else
    echo "_No tags were available when this was generated._"
    echo
  fi
} > "$notes"
echo "generated $(basename "$notes")"
