// Database column names, read out of SR_GameServer.exe.
//
// The server carries its runtime schema as a contiguous, 4-byte-aligned string
// pool in .rdata at 0x00b11b08..0x00b12a70 -- 310 identifiers, of which 54 are
// table names and the rest are column names.
//
// WHY IT IS THERE, and why the names are usable while the indices are not.
// Database::FUN_00972b40 binds a table's schema by NAME: it asks ODBC for each
// column, then walks the table's own 0x54-byte column records comparing the
// record's declared name (an SSO string at +0x04) against the one ODBC
// reported, with CompareStringA. On a match it writes the column INDEX from
// ODBC into the record at +0x30. So the binary declares the names and the live
// database supplies the ordinals -- which is why a static column index is not
// recoverable from the executable and a column NAME is.
//
// THE POOL IS DEDUPLICATED, and that limits what may be read off it. Each name
// appears once, at first use, so TableColumns gives the names a table
// INTRODUCES -- not its full column list. _TIMEDJOBFORPET and
// _INVENTORYFORAVATAR list nothing at all because every name they use was
// already pooled by _TIMEDJOB and _INVENTORY. Shared names (ID, CharID, Slot,
// Data1, Data2) belong to many tables.
//
// See docs/protocol/db_columns.md.
