// OffsetOf returns the struct offset of a column, and whether it is known.
func OffsetOf(table, column string) (int, bool) {
	for _, c := range ColumnOffsets {
		if c.Table == table && c.Column == column {
			return c.Offset, true
		}
	}
	return 0, false
}

// ColumnAt is the reverse: which column a struct offset belongs to.
func ColumnAt(table string, offset int) (string, bool) {
	for _, c := range ColumnOffsets {
		if c.Table == table && c.Offset == offset {
			return c.Column, true
		}
	}
	return "", false
}
