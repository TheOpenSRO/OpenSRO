package mana

import (
	"testing"
	"time"
)

func TestSpendRestoreRefillClear(t *testing.T) {
	tr := NewTracker()
	const max = 120

	// A character not seen before starts full.
	if got := tr.Current(1, max); got != max {
		t.Fatalf("a fresh character should start full: got %d, want %d", got, max)
	}
	// A cost that is affordable is taken.
	rem, ok := tr.Spend(1, max, 50)
	if !ok || rem != 70 {
		t.Fatalf("spending 50 of 120: got remaining=%d ok=%v", rem, ok)
	}
	// A cost that is not affordable takes nothing and reports it.
	rem, ok = tr.Spend(1, max, 100)
	if ok {
		t.Fatalf("spending 100 with 70 left should fail, got ok=true")
	}
	if rem != 70 {
		t.Fatalf("a refused spend must not take mana: got %d, want 70", rem)
	}
	// A free skill always succeeds and takes nothing.
	if rem, ok = tr.Spend(1, max, 0); !ok || rem != 70 {
		t.Fatalf("a zero cost: got remaining=%d ok=%v", rem, ok)
	}
	// The tracker regenerates nothing on its own any more: the tick does
	// (session.RunRegen), because the rate depends on the motion state.
	if got := tr.Current(1, max); got != 70 {
		t.Fatalf("the tracker regenerated by itself: got %d, want 70", got)
	}
	// Restore never overfills.
	if got := tr.Restore(1, max, 30); got != 100 {
		t.Fatalf("restoring 30 to 70: got %d, want 100", got)
	}
	if got := tr.Restore(1, max, 1000); got != max {
		t.Fatalf("a restore past the maximum: got %d, want %d", got, max)
	}
	// A shrunken pool clamps rather than reporting more than the maximum.
	if got := tr.Current(1, 50); got != 50 {
		t.Fatalf("a smaller max should clamp: got %d, want 50", got)
	}
	// Refill and Clear.
	tr.Spend(1, max, 60)
	tr.Refill(1, max)
	if got := tr.Current(1, max); got != max {
		t.Fatalf("after Refill: got %d, want %d", got, max)
	}
	tr.Spend(1, max, 60)
	tr.Clear(1)
	if got := tr.Current(1, max); got != max {
		t.Fatalf("a cleared character starts full again: got %d", got)
	}
}

// The interval is the engine's own, read off the timer registration.
func TestRegenIntervalIsTheEnginesFour(t *testing.T) {
	if RegenInterval != 4*time.Second {
		t.Errorf("RegenInterval = %v, want 4s (.rdata 0x00b45dc0 = 4.0)", RegenInterval)
	}
}

// The two rates are the floats SetMotionState writes: 0.8 (.rdata 0x00b45b94)
// and 8.0 (.rdata 0x00b45e14). Pinned as their float32 bit patterns, which is
// what the .rdata holds.
func TestRegenRatesAreTheEnginesFloats(t *testing.T) {
	if got := StandRegenPercent; got != float32(0.8) {
		t.Errorf("StandRegenPercent = %v, want float32(0.8)", got)
	}
	if got := SitRegenPercent; got != 8.0 {
		t.Errorf("SitRegenPercent = %v, want 8.0", got)
	}
	if RegenHalfCap != 0.5 {
		t.Errorf("RegenHalfCap = %v, want 0.5 (.rdata 0x00b45c50)", RegenHalfCap)
	}
}

// A tick is a percentage of the MAXIMUM pool (vtable slot 0x110 is
// ftol(EvaluateParam(3)) in CGObjPC's vtable), so it does not depend on how full
// the pool is -- the function does not even take the current value.
func TestRegenPerTickIsAPercentageOfTheMaximum(t *testing.T) {
	for _, tc := range []struct {
		max  int
		rate float32
		want int
	}{
		{1000, StandRegenPercent, 8}, // 8.00000011920929
		{1000, SitRegenPercent, 80},
		{200, StandRegenPercent, 1}, // 1.6 truncates to 1
		{200, SitRegenPercent, 16},
		{5000, StandRegenPercent, 40},
		{5000, SitRegenPercent, 400},
		{12345, SitRegenPercent, 987}, // 987.6 truncates
	} {
		if got := RegenPerTick(tc.max, tc.rate); got != tc.want {
			t.Errorf("RegenPerTick(%d, %v) = %d, want %d", tc.max, tc.rate, got, tc.want)
		}
	}
}

// The floor at 1 and the cap at half the maximum, in the engine's order: the
// floor first, then clamp(amount, 0, trunc(max*0.5)).
func TestRegenPerTickFloorAndCap(t *testing.T) {
	// Below 125 the standing rate truncates to 0 and only the floor makes it 1.
	for _, max := range []int{2, 3, 50, 124} {
		if got := RegenPerTick(max, StandRegenPercent); got != 1 {
			t.Errorf("RegenPerTick(%d, 0.8f) = %d, want the floor 1", max, got)
		}
	}
	// A pool of 1 has a cap of 0, which takes the floor back off.
	if got := RegenPerTick(1, SitRegenPercent); got != 0 {
		t.Errorf("RegenPerTick(1, 8) = %d, want 0 -- trunc(1 x 0.5) is 0", got)
	}
	// No pool, nothing.
	if got := RegenPerTick(0, SitRegenPercent); got != 0 {
		t.Errorf("RegenPerTick(0, 8) = %d, want 0", got)
	}
	// The cap is half the MAXIMUM, so at the real rates it never binds above
	// a pool of 1: a rate of 60% would be capped at 50%.
	if got := RegenPerTick(1000, 60); got != 500 {
		t.Errorf("RegenPerTick(1000, 60) = %d, want the cap 500", got)
	}
}
