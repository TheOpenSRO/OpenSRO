// refine names the group of a constant in a file that mixes areas: proto's
// opcodes.go holds the handshake and gateway login, the movement request and
// the academy.
func refine(group, rel, name string) string {
	if !strings.HasPrefix(rel, "internal/proto/") {
		return group
	}
	switch {
	case strings.Contains(name, "Handshake"), strings.Contains(name, "Gateway"), strings.Contains(name, "Agent"),
		strings.Contains(name, "Login"):
		return "login"
	case strings.Contains(name, "Academy"):
		return "social"
	}
	return "world"
}

// Group is the handler group of the file at rel (slash-separated, relative to
// the server module): "world" for movement, arrival, teleports and the like,
// "other" when no rule names it.
func Group(rel string) string {
	parts := strings.Split(rel, "/")
	if len(parts) >= 3 && parts[0] == "internal" && parts[1] != "session" {
		if g, ok := packageGroups[parts[1]]; ok {
			return g
		}
		return "other"
	}
	stem := strings.TrimSuffix(parts[len(parts)-1], ".go")
	for _, r := range stemGroups {
		if strings.HasPrefix(stem, r.prefix) {
			return r.group
		}
	}
	switch {
	case parts[0] == "cmd":
		return "other"
	case strings.HasPrefix(stem, "world"), strings.HasPrefix(stem, "arrival"), strings.HasPrefix(stem, "playerview"),
		strings.HasPrefix(stem, "aoi"), strings.HasPrefix(stem, "destmove"), strings.HasPrefix(stem, "motion"),
		strings.HasPrefix(stem, "emote"), strings.HasPrefix(stem, "trace"), strings.HasPrefix(stem, "unstuck"),
		strings.HasPrefix(stem, "teleport"), strings.HasPrefix(stem, "recall"), strings.HasPrefix(stem, "deadstate"),
		strings.HasPrefix(stem, "celestial"), strings.HasPrefix(stem, "ping"), strings.HasPrefix(stem, "walkin"),
		strings.HasPrefix(stem, "dungeon"), strings.HasPrefix(stem, "position"), strings.HasPrefix(stem, "restriction"),
		strings.HasPrefix(stem, "stats"), strings.HasPrefix(stem, "wire"), strings.HasPrefix(stem, "navmesh"),
		strings.HasPrefix(stem, "safezone"), strings.HasPrefix(stem, "history"):
		return "world"
	}
	return "other"
}
