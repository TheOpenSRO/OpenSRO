// Package opcodescan finds every opcode constant the server's code names
// (round 858, OURS), for the metrics package's opcode label: a packet whose
// opcode is in the table is counted under its own hex, any other under
// "other", so a client sending random opcodes cannot grow the label set.
//
// An opcode constant is a const whose name is Op... (or a lower-case prefix
// then Op..., e.g. legacyOpCharacterList) and whose value is a hex literal of
// at most 0xFFFF, plain or converted (uint16(0x7021)). Its group is the area
// of the file that names it (Group). cmd/server and internal/... are scanned,
// tests excluded.
package opcodescan

import (
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// Entry is one opcode and its handler group.
type Entry struct {
	Opcode uint16
	Group  string
}

var opName = regexp.MustCompile(`^([a-z][a-zA-Z]*)?Op[A-Z0-9]`)

// Scan walks serverRoot's internal/ and cmd/server and returns every opcode
// once, sorted, its group taken from the first file (in path order) that
// names it.
func Scan(serverRoot string) ([]Entry, error) {
	var files []string
	for _, dir := range []string{"internal", filepath.Join("cmd", "server")} {
		root := filepath.Join(serverRoot, dir)
		err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() {
				if strings.Contains(path, filepath.Join("internal", "metrics")) {
					return filepath.SkipDir
				}
				return nil
			}
			if strings.HasSuffix(path, ".go") && !strings.HasSuffix(path, "_test.go") {
				files = append(files, path)
			}
			return nil
		})
		if err != nil {
			return nil, err
		}
	}
	// The session package's files first: it is where the handlers live,
	// so its file names the group when another package names the opcode too.
	sessionDir := filepath.Join("internal", "session") + string(filepath.Separator)
	sort.Slice(files, func(i, j int) bool {
		si, sj := strings.Contains(files[i], sessionDir), strings.Contains(files[j], sessionDir)
		if si != sj {
			return si
		}
		return files[i] < files[j]
	})
	seen := map[uint16]string{}
	fset := token.NewFileSet()
	for _, path := range files {
		src, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		f, err := parser.ParseFile(fset, path, src, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		rel, _ := filepath.Rel(serverRoot, path)
		group := Group(filepath.ToSlash(rel))
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.CONST {
				continue
			}
			for _, spec := range gd.Specs {
				vs := spec.(*ast.ValueSpec)
				for i, name := range vs.Names {
					if i >= len(vs.Values) || !opName.MatchString(name.Name) {
						continue
					}
					v, ok := hexValue(vs.Values[i])
					if !ok {
						continue
					}
					if _, dup := seen[v]; !dup {
						seen[v] = refine(group, filepath.ToSlash(rel), name.Name)
					}
				}
			}
		}
	}
	out := make([]Entry, 0, len(seen))
	for op, g := range seen {
		out = append(out, Entry{Opcode: op, Group: g})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Opcode < out[j].Opcode })
	return out, nil
}

// Render is the generated Go source of the metrics package's table.
func Render(entries []Entry) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by opcodegen (go generate ./internal/metrics); DO NOT EDIT.\n\n")
	b.WriteString("package metrics\n\n")
	b.WriteString("// knownOpcodes is every opcode the server's code names, with its handler\n// group (opcodescan.Group).\n")
	b.WriteString("var knownOpcodes = map[uint16]string{\n")
	for _, e := range entries {
		b.WriteString("\t0x")
		b.WriteString(strings.ToUpper(strconv.FormatUint(uint64(e.Opcode)|0x10000, 16)[1:]))
		b.WriteString(": ")
		b.WriteString(strconv.Quote(e.Group))
		b.WriteString(",\n")
	}
	b.WriteString("}\n")
	return []byte(b.String())
}

func hexValue(e ast.Expr) (uint16, bool) {
	if c, ok := e.(*ast.CallExpr); ok && len(c.Args) == 1 {
		e = c.Args[0]
	}
	lit, ok := e.(*ast.BasicLit)
	if !ok || lit.Kind != token.INT || !strings.HasPrefix(strings.ToLower(lit.Value), "0x") {
		return 0, false
	}
	v, err := strconv.ParseUint(lit.Value[2:], 16, 32)
	if err != nil || v > 0xFFFF {
		return 0, false
	}
	return uint16(v), true
}

