#!/usr/bin/env python3
"""opcode -> subsystem, from the class names of its senders.

An opcode's senders are in docs/protocol/payload_layouts.tsv. Where the named
ones all belong to one subsystem, the opcode does too.

Round 475 grouped by EXACT class prefix and missed its own best case: 0x34d2 has
23 senders, all battle arena, but CBattleArenaInfoFlag and CBattleArenaInfoPoint
are different prefixes, so exact equality rejected the strongest evidence in the
set. This groups by a normalised STEM instead -- uppercase, drop the MSVC leading
C, drop underscores, then take the longest common prefix -- so
CBattleArenaInfoFlag and BATTLE_ARENA_EVENT_HANDLERS both reduce to BATTLEARENA.

A stem shorter than MIN_STEM is not evidence, and neither is a single sender.
"""
import re, sys, collections

MIN_STEM = 8
GENERIC = {"GOBJPC", "MAINPROCESS", "GAMESERVER", "GOBJCHAR", "GOBJ"}

def klass(name):
    if "::" in name:
        return name.split("::")[0]
    m = re.match(r"^([A-Za-z][A-Za-z0-9]*?)_[A-Z]", name)
    return m.group(1) if m else None

def stem(k):
    s = k.upper().replace("_", "")
    if len(s) > 1 and k[0] == "C" and k[1:2].isupper():
        s = s[1:]
    return s

def lcp(items):
    if not items: return ""
    out = items[0]
    for s in items[1:]:
        i = 0
        while i < len(out) and i < len(s) and out[i] == s[i]:
            i += 1
        out = out[:i]
    return out

def main(path):
    senders = collections.defaultdict(set)
    for line in open(path):
        if line.startswith("#") or line.startswith("opcode"): continue
        p = line.rstrip("\n").split("\t")
        if len(p) < 2 or not p[0].startswith("0x"): continue
        for op in p[0].lower().split("+"):
            senders[op].add(p[1])

    rows = []
    for op, ss in senders.items():
        named = [s for s in ss if not re.fullmatch(r"FUN_[0-9a-f]{8}", s)]
        stems = [stem(k) for k in (klass(s) for s in named) if k]
        stems = [s for s in stems if s and s not in GENERIC]
        if len(stems) < 2:
            continue
        common = lcp(sorted(stems))
        if len(common) < MIN_STEM:
            continue
        rows.append((op, common, len(stems), len(ss)))

    print("# opcode -> subsystem, from the normalised STEM shared by its named senders'")
    print("# classes in payload_layouts.tsv. Generated by tools/opcode_subsystems.py.")
    print("# An opcode appears only when >=2 named senders share a stem of >=%d characters." % MIN_STEM)
    print("# Generic module attributions (GObjPC, CMainProcess, ...) are excluded: they say")
    print("# where a function lives, not which subsystem owns the opcode.")
    print("# strength = how many named senders share that stem.")
    print("opcode\tsubsystem_stem\tstrength\tsenders")
    for r in sorted(rows, key=lambda r: (-r[2], r[0])):
        print("%s\t%s\t%d\t%d" % r)
    print("# opcodes attributed: %d" % len(rows), file=sys.stderr)

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "docs/protocol/payload_layouts.tsv")
